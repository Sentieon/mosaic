"""Generate the Fisher-test expectation table of the joint caller's
``fisher.rs``.

Writes OUT with one line per distinct ``sb`` table of PostgreSQL's
``site_info``: ``sb1 sb2 sb3 sb4 <scipy p, hex bits> <FS, hex bits>``
(tab-separated), FS as the Python engine wrote it (its
``calculate_info_fields``, kept here as ``python_fs`` since the engine's
removal), sorted by the table. With
``--max N`` at most N tables, evenly spaced over the sorted list (the
checked-in table; the full list is the measurement, which the Rust test
reads from ``MOSAIC_FISHER_TABLE`` when that is set).

Run with the project's Python environment and PYTHONPATH at the repo
root, under the
``MOSAIC_DB_*`` of the store:
    python rust/tools/gen_fisher_table.py OUT [--max N]
"""

import argparse
import math
import struct

import psycopg2
from scipy.stats import fisher_exact

from mosaic.config import DB_CONFIG


def bits(x: float) -> str:
    return "%016x" % struct.unpack("<Q", struct.pack("<d", x))[0]


def python_fs(sb: list) -> float:
    """FS of the removed Python engine's ``calculate_info_fields``: scipy's
    two-sided p of ``[[sb1, sb2], [sb3, sb4]]``, ``-10 * log10(max(p,
    1e-30))``, rounded as its ``_round3`` (``round(x, 3) + 0.0``: no
    negative zero)."""
    _, pv = fisher_exact([[sb[0], sb[1]], [sb[2], sb[3]]])
    return round(-10.0 * math.log10(max(pv, 1e-30)), 3) + 0.0


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("out")
    ap.add_argument("--max", type=int, default=0)
    args = ap.parse_args()
    out = args.out
    conn = psycopg2.connect(**DB_CONFIG)
    with conn, conn.cursor() as cur:
        cur.execute("SELECT DISTINCT sb FROM site_info WHERE sb IS NOT NULL")
        tables = sorted(tuple(r[0]) for r in cur)
    conn.close()
    n_all = len(tables)
    if args.max and n_all > args.max:
        step = n_all / args.max
        tables = [tables[int(i * step)] for i in range(args.max)]
    with open(out, "w") as fh:
        fh.write(
            "# generated by rust/tools/gen_fisher_table.py: "
            f"{len(tables)} of the {n_all} distinct site_info.sb tables; "
            "sb1 sb2 sb3 sb4 p_bits fs_bits\n"
        )
        for sb in tables:
            _, p = fisher_exact([[sb[0], sb[1]], [sb[2], sb[3]]])
            fs = python_fs(list(sb))
            fh.write("\t".join(map(str, sb)))
            fh.write(f"\t{bits(float(p))}\t{bits(fs)}\n")
    print(f"{len(tables)} of {n_all} tables -> {out}")


if __name__ == "__main__":
    main()
